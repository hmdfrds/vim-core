    fn registry_user_defined_overrides_builtin() {
        let mut reg = DigraphRegistry::new();
        // Built-in: ('a', '\'') -> 'á'. Override with custom 'X'.
        reg.add('a', '\'', 'X');
        assert_eq!(reg.lookup('a', '\''), Some('X'));
    }

    #[test]
    fn registry_user_defined_new_pair() {
        let mut reg = DigraphRegistry::new();
        // No built-in for ('z', 'z'), but user defines it.
        assert_eq!(lookup_digraph('z', 'z'), None);
        reg.add('z', 'z', 'Z');
        assert_eq!(reg.lookup('z', 'z'), Some('Z'));
    }

    #[test]
    fn registry_fallback_to_builtin() {
        let reg = DigraphRegistry::new();
        // No user-defined, built-in should work.
        assert_eq!(reg.lookup('a', '\''), Some('á'));
        assert_eq!(reg.lookup('N', '~'), Some('Ñ'));
    }

    #[test]
    fn registry_both_orderings_work() {
        let mut reg = DigraphRegistry::new();
        reg.add('x', 'y', '!');
        // Forward ordering
        assert_eq!(reg.lookup('x', 'y'), Some('!'));
        // Reverse ordering
        assert_eq!(reg.lookup('y', 'x'), Some('!'));
    }

    #[test]
    fn registry_clear_resets_to_builtin() {
        let mut reg = DigraphRegistry::new();
        reg.add('a', '\'', 'X');
        assert_eq!(reg.lookup('a', '\''), Some('X'));

        reg.clear();
        // After clear, falls back to built-in.
        assert_eq!(reg.lookup('a', '\''), Some('á'));
    }

    #[test]
    fn registry_custom_count() {
        let mut reg = DigraphRegistry::new();
        assert_eq!(reg.custom_count(), 0);
        reg.add('a', 'b', 'c');
        assert_eq!(reg.custom_count(), 1);
        reg.add('x', 'y', 'z');
        assert_eq!(reg.custom_count(), 2);
        reg.clear();
        assert_eq!(reg.custom_count(), 0);
    }

    #[test]
    fn registry_overwrite_same_pair() {
        let mut reg = DigraphRegistry::new();
        reg.add('a', 'b', 'X');
        assert_eq!(reg.lookup('a', 'b'), Some('X'));
        reg.add('a', 'b', 'Y');
        assert_eq!(reg.lookup('a', 'b'), Some('Y'));
    }

    #[test]
    fn registry_unknown_returns_none() {
        let reg = DigraphRegistry::new();
        // Neither user-defined nor built-in.
        assert_eq!(reg.lookup('z', 'z'), None);
    }
