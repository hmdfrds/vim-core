/// Lazily-built hash map for O(1) digraph lookups.
///
/// Built on first access from the 1334-entry `DIGRAPH_TABLE`. Both orderings
/// of each key pair are inserted so that lookup is a single `get()`.
static DIGRAPH_MAP: std::sync::LazyLock<ahash::AHashMap<(char, char), char>> =
    std::sync::LazyLock::new(|| {
        let mut map = ahash::AHashMap::with_capacity(DIGRAPH_TABLE.len() * 2);
        for &((c1, c2), result) in DIGRAPH_TABLE {
            // Insert primary ordering. For reversed ordering, only insert if
            // no entry already exists (first-match semantics match original
            // linear scan which found the first table entry matching either order).
            map.entry((c1, c2)).or_insert(result);
            map.entry((c2, c1)).or_insert(result);
        }
        map
    });

/// Look up a digraph by its two-character sequence in the built-in table.
///
/// Tries both orderings: `(c1, c2)` and `(c2, c1)`.
/// Returns `None` if no digraph matches.
///
/// Uses a lazily-built `AHashMap` for O(1) lookup instead of the original
/// O(1334) linear scan over `DIGRAPH_TABLE`.
#[must_use]
pub fn lookup_digraph(c1: char, c2: char) -> Option<char> {
    DIGRAPH_MAP.get(&(c1, c2)).copied()
}

// ─────────────────────────────────────────────────────────────────────────────
// Runtime digraph registry (user-defined digraphs)
// ─────────────────────────────────────────────────────────────────────────────

use std::collections::HashMap;

/// Runtime digraph registry for user-defined digraphs.
///
/// Checked **before** the compile-time const table so user definitions
/// take precedence over built-in RFC 1345 digraphs. Lives on `VimEngine`
/// alongside `VimOptions` — the execution layer performs the lookup during
/// the insert pre-compute phase.
#[derive(Debug, Clone, Default)]
pub struct DigraphRegistry {
    custom: HashMap<(char, char), char>,
}

impl DigraphRegistry {
    /// Create an empty registry (built-in table still active via fallback).
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Add a user-defined digraph.
    ///
    /// Overwrites any previous user definition for the same pair.
    pub fn add(&mut self, c1: char, c2: char, result: char) {
        self.custom.insert((c1, c2), result);
    }

    /// Remove all user-defined digraphs.
    ///
    /// After calling this, only the built-in table is consulted.
    pub fn clear(&mut self) {
        self.custom.clear();
    }

    /// Number of user-defined digraphs currently registered.
    #[must_use]
    pub fn custom_count(&self) -> usize {
        self.custom.len()
    }

    /// Look up a digraph — user-defined first, then built-in table.
    ///
    /// Tries both orderings `(c1, c2)` and `(c2, c1)` in the user-defined
    /// map (matching Vim's `:digraphs` reverse-lookup behaviour), then falls
    /// back to the compile-time `DIGRAPH_TABLE`.
    #[must_use]
    pub fn lookup(&self, c1: char, c2: char) -> Option<char> {
        // User-defined takes precedence (both orderings)
        if let Some(&ch) = self.custom.get(&(c1, c2)) {
            return Some(ch);
        }
        if let Some(&ch) = self.custom.get(&(c2, c1)) {
            return Some(ch);
        }
        // Fall back to built-in table
        lookup_digraph(c1, c2)
    }
}

